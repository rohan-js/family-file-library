-- Resolve TV device identity from Supabase Auth user or custom header 'x-device-token'
create or replace function public.get_auth_device_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select id from public.devices
  where is_revoked = false
    and (
      (auth.uid() is not null and auth_user_id = auth.uid())
      or (
        nullif(coalesce(nullif(current_setting('request.headers', true), ''), '{}')::json->>'x-device-token', '') is not null
        and device_token_hash = encode(sha256((coalesce(nullif(current_setting('request.headers', true), ''), '{}')::json->>'x-device-token')::bytea), 'hex')
      )
    )
  limit 1;
$$;

-- Core Access Check: Returns true if caller is a member OR an authorized TV device for the space
create or replace function public.has_space_access(p_space_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select (
    -- 1. Family member check via Supabase Auth
    exists (
      select 1 from public.members
      where space_id = p_space_id
        and user_id = auth.uid()
    )
    -- 2. Paired TV device check
    or exists (
      select 1 from public.devices
      where space_id = p_space_id
        and id = public.get_auth_device_id()
        and is_revoked = false
    )
  );
$$;

-- Check if caller is specifically an authenticated family user (phone/web member)
create or replace function public.is_space_member_user(p_space_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.members
    where space_id = p_space_id
      and user_id = auth.uid()
  );
$$;

-- Check if caller is space owner or admin
create or replace function public.is_space_admin(p_space_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.members
    where space_id = p_space_id
      and user_id = auth.uid()
      and role in ('owner', 'admin')
  );
$$;

-- Check if caller is a paired TV device
create or replace function public.is_tv_device(p_space_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.devices
    where space_id = p_space_id
      and id = public.get_auth_device_id()
      and is_revoked = false
  );
$$;

