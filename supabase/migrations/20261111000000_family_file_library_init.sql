-- ----------------------------------------------------------------------------
-- SPACES Policies
-- ----------------------------------------------------------------------------
create policy "spaces_select"
  on public.spaces for select
  using (public.has_space_access(id) or created_by = auth.uid());

create policy "spaces_insert"
  on public.spaces for insert
  with check (
    auth.uid() is not null
    and (created_by is null or created_by = auth.uid())
  );

create policy "spaces_update"
  on public.spaces for update
  using (public.is_space_admin(id))
  with check (public.is_space_admin(id));

create policy "spaces_delete"
  on public.spaces for delete
  using (
    exists (
      select 1 from public.members
      where space_id = spaces.id
        and user_id = auth.uid()
        and role = 'owner'
    )
    or (
      created_by = auth.uid()
      and not exists (select 1 from public.members where space_id = spaces.id)
    )
  );

-- ----------------------------------------------------------------------------
-- MEMBERS Policies
-- ----------------------------------------------------------------------------
create policy "members_select"
  on public.members for select
  using (public.has_space_access(space_id));

create policy "members_insert"
  on public.members for insert
  with check (
    -- Allow initial space creator to establish first owner membership row, or admin to insert new members
    public.is_space_admin(space_id)
    or (
      auth.uid() = user_id
      and exists (
        select 1 from public.spaces s
        where s.id = space_id
          and s.created_by = auth.uid()
          and not exists (select 1 from public.members m where m.space_id = s.id)
      )
    )
  );

create policy "members_update"
  on public.members for update
  using (public.is_space_admin(space_id) or auth.uid() = user_id)
  with check (
    -- Admins can update any member; regular members can only update their own display_name without role self-escalation
    public.is_space_admin(space_id)
    or (auth.uid() = user_id and role = (select m.role from public.members m where m.id = members.id))
  );

create policy "members_delete"
  on public.members for delete
  using (public.is_space_admin(space_id) or auth.uid() = user_id);

