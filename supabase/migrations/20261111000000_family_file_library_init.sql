  on public.devices for select
  using (public.has_space_access(space_id));

create policy "devices_insert"
  on public.devices for insert
  with check (public.is_space_admin(space_id));

create policy "devices_update"
  on public.devices for update
  using (public.is_space_admin(space_id) or id = public.get_auth_device_id())
  with check (
    -- Admins can update any device attribute; paired TV devices can only update heartbeat without modifying token/revocation
    public.is_space_admin(space_id)
    or (
      id = public.get_auth_device_id()
      and is_revoked = false
      and device_token_hash = (select d.device_token_hash from public.devices d where d.id = devices.id)
      and space_id = (select d.space_id from public.devices d where d.id = devices.id)
    )
  );

