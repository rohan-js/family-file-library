-- Function to permanently purge soft-deleted files and folders older than 30 days
create or replace function public.cleanup_expired_trash()
returns table(purged_files_count int, purged_folders_count int)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_files int := 0;
  v_folders int := 0;
begin
  -- 1. Purge expired files (30+ days in trash)
  with expired_files as (
    select id
    from public.files
    where deleted_at is not null
      and deleted_at < (now() - interval '30 days')
  ),
  del_files as (
    delete from public.files
    where id in (select id from expired_files)
    returning id
  )
  select count(*) into v_files from del_files;

  -- 2. Purge expired folders (30+ days in trash)
  with del_folders as (
    delete from public.folders
    where deleted_at is not null
      and deleted_at < (now() - interval '30 days')
    returning id
  )
  select count(*) into v_folders from del_folders;

  -- 3. Purge expired notes (30+ days in trash)
  delete from public.notes
  where deleted_at is not null
    and deleted_at < (now() - interval '30 days');

  -- 4. Purge stale pairing codes (> 24 hours expired)
  delete from public.pairing_codes
  where expires_at < (now() - interval '24 hours');

  return query select v_files, v_folders;
end;
$$;

-- Keep-alive ping RPC invoked by scheduled GitHub Action
create or replace function public.health_check_ping()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_active_spaces int;
  v_purged record;
begin
  -- Query active spaces to trigger database I/O and reset Supabase pause timer
  select count(*) into v_active_spaces from public.spaces;

  -- Execute garbage collection of expired trash items (> 30 days)
  select purged_files_count, purged_folders_count into v_purged from public.cleanup_expired_trash();

  return jsonb_build_object(
    'status', 'healthy',
    'timestamp', now(),
    'active_spaces_count', v_active_spaces,
    'trash_files_purged', v_purged.purged_files_count,
    'trash_folders_purged', v_purged.purged_folders_count
  );
end;
$$;

