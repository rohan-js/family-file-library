-- Table 1: spaces (Family / shared library space)
create table if not exists public.spaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 100),
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  pin_hash text, -- Salted hash for 4-6 digit PIN lock on TV
  pin_updated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Table 2: members (Maps authenticated users to spaces with roles)
create table if not exists public.members (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member')),
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_members_space_user unique (space_id, user_id)
);

-- Table 3: invites (Space invitations for family members via email)
create table if not exists public.invites (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  email text not null check (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
  invited_by uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('admin', 'member')),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'rejected', 'expired')),
  token text not null unique default encode(gen_random_bytes(24), 'hex'),
  expires_at timestamptz not null default (now() + interval '7 days'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_invites_space_email unique (space_id, email)
);

-- Table 4: devices (Paired hardware devices, e.g. Android TV)
create table if not exists public.devices (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  device_identifier text not null, -- Hardware or app installation UUID
  device_name text not null check (char_length(trim(device_name)) between 1 and 100),
  device_type text not null default 'android_tv' check (device_type in ('android_tv', 'phone', 'tablet', 'web')),
  auth_user_id uuid references auth.users(id) on delete cascade, -- Optional dedicated device auth user
  device_token_hash text not null, -- SHA-256 hash of device secret/bearer token
  last_seen_at timestamptz,
  paired_by uuid references auth.users(id) on delete set null,
  paired_at timestamptz not null default now(),
  is_revoked boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_devices_space_identifier unique (space_id, device_identifier)
);

-- Table 5: pairing_codes (Ephemeral handshake for TV code-based pairing)
create table if not exists public.pairing_codes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[A-Z0-9]{6,8}$'),
  device_identifier text not null,
  device_name text not null default 'Android TV',
  device_secret_hash text not null, -- Hashed secret generated by device to claim pairing
  status text not null default 'pending' check (status in ('pending', 'approved', 'claimed', 'expired', 'rejected')),
  space_id uuid references public.spaces(id) on delete cascade,
  approved_by uuid references auth.users(id) on delete set null,
  device_credentials jsonb, -- Temporary payload with device_token handed to TV upon claim
  expires_at timestamptz not null default (now() + interval '10 minutes'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Table 6: folders (Hierarchical folder tree per space)
create table if not exists public.folders (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  parent_id uuid references public.folders(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 120 and name !~ '[/\\:*?"<>|]'),
  color text check (color is null or color ~ '^#[0-9A-Fa-f]{6}$'),
  icon text,
  created_by uuid references auth.users(id) on delete set null,
  deleted_at timestamptz default null, -- Trash logic (soft delete)
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Table 7: files (File metadata, conversion state, extracted text, and trash status)
create table if not exists public.files (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  folder_id uuid references public.folders(id) on delete set null, -- null = Inbox / Root
  name text not null check (char_length(trim(name)) between 1 and 255),
  file_type text not null, -- MIME type, e.g. 'application/pdf', 'image/jpeg'
  file_category text not null check (file_category in ('pdf', 'image', 'office', 'text', 'other')),
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 52428800), -- <= 50MB
  storage_path text not null unique, -- Bucket path: '<space_id>/original/<file_id>/<filename>'
  pdf_path text, -- Converted PDF path for Office docs: '<space_id>/converted/<file_id>.pdf'
  text_content text, -- Extracted text for search & TTS read-aloud
  conversion_status text not null default 'ready' check (conversion_status in ('pending', 'processing', 'ready', 'failed', 'not_applicable')),
  conversion_error text,
  uploader_id uuid references auth.users(id) on delete set null,
  uploader_name text not null default 'Family Member',
  view_count integer not null default 0 check (view_count >= 0),
  last_viewed_at timestamptz,
  deleted_at timestamptz default null, -- Trash logic (soft delete)
  deleted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  fts tsvector generated always as (to_tsvector('english', coalesce(name, '') || ' ' || substr(coalesce(text_content, ''), 1, 50000))) stored
);

-- Table 8: notes (Annotations attached to files or folders)
create table if not exists public.notes (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  file_id uuid references public.files(id) on delete cascade,
  folder_id uuid references public.folders(id) on delete cascade,
  author_id uuid references auth.users(id) on delete set null,
  author_device_id uuid references public.devices(id) on delete set null,
  author_name text not null default 'Family Member',
  content text not null check (char_length(trim(content)) > 0),
  page_number integer check (page_number is null or page_number >= 1),
  deleted_at timestamptz default null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_notes_target check (file_id is not null or folder_id is not null)
);

-- Table 9: favorites (Starred files by user or TV device)
create table if not exists public.favorites (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  file_id uuid not null references public.files(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  device_id uuid references public.devices(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint ck_favorites_actor check (user_id is not null or device_id is not null)
