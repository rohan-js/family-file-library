-- Function 1: TV calls this unauthenticated to generate an 8-character code and secret
create or replace function public.request_tv_pairing_code(
  p_device_identifier text,
  p_device_name text default 'Android TV'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_secret text;
  v_expires_at timestamptz;
  v_chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; -- Avoid confusing 0/O, 1/I
  v_i int;
begin
  if trim(coalesce(p_device_identifier, '')) = '' then
    raise exception 'device_identifier is required';
  end if;

  -- Generate 6-character human-friendly alphanumeric code
  -- Check globally across pairing_codes to satisfy unique constraint
  loop
    v_code := '';
    for v_i in 1..6 loop
      v_code := v_code || substr(v_chars, floor(random() * length(v_chars) + 1)::int, 1);
    end loop;
    exit when not exists (select 1 from public.pairing_codes where code = v_code);
  end loop;

  -- Generate 32-byte cryptographically secure secret
  v_secret := encode(gen_random_bytes(32), 'hex');
  v_expires_at := now() + interval '10 minutes';

  -- Upsert pairing attempt for this device
  delete from public.pairing_codes
  where device_identifier = p_device_identifier
    and status in ('pending', 'expired');

  insert into public.pairing_codes (
    code,
    device_identifier,
    device_name,
    device_secret_hash,
    status,
    expires_at
  ) values (
    v_code,
    p_device_identifier,
    coalesce(nullif(trim(p_device_name), ''), 'Android TV'),
    encode(sha256(v_secret::bytea), 'hex'),
    'pending',
    v_expires_at
  );

  return jsonb_build_object(
    'code', v_code,
    'device_secret', v_secret,
    'expires_at', v_expires_at
  );
end;
$$;

-- Function 2: Authenticated family member enters the code to pair the TV to their space
create or replace function public.approve_tv_pairing_code(
  p_code text,
  p_space_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_clean_code text;
  v_pairing record;
  v_device_id uuid;
  v_device_token text;
  v_token_hash text;
begin
  -- Validate caller has access to space
  if not public.is_space_member_user(p_space_id) then
    raise exception 'Access denied: caller is not a member of the requested space';
  end if;

  -- Sanitize input: strip hyphens and whitespace (e.g. 'ABC-DEF' -> 'ABCDEF')
  v_clean_code := regexp_replace(upper(trim(p_code)), '[\s-]+', '', 'g');

  -- Locate valid pairing code
  select * into v_pairing
  from public.pairing_codes
  where code = v_clean_code
    and status = 'pending'
    and expires_at > now()
  for update;

  if not found then
    raise exception 'Invalid or expired pairing code';
  end if;

  -- Generate high-entropy bearer token for TV device
  v_device_token := encode(gen_random_bytes(48), 'hex');
  v_token_hash := encode(sha256(v_device_token::bytea), 'hex');

  -- Upsert device record in devices table
  insert into public.devices (
    space_id,
    device_identifier,
    device_name,
    device_type,
    device_token_hash,
    paired_by,
    paired_at,
    is_revoked,
    last_seen_at
  ) values (
    p_space_id,
    v_pairing.device_identifier,
    v_pairing.device_name,
    'android_tv',
    v_token_hash,
    auth.uid(),
    now(),
    false,
    now()
  )
  on conflict (space_id, device_identifier) do update set
    device_name = excluded.device_name,
    device_token_hash = excluded.device_token_hash,
    paired_by = excluded.paired_by,
    paired_at = excluded.paired_at,
    is_revoked = false,
    last_seen_at = excluded.last_seen_at,
    updated_at = now()
  returning id into v_device_id;

  -- Mark pairing code as approved and stage device credentials for handshake claim
  update public.pairing_codes
  set
    status = 'approved',
    space_id = p_space_id,
    approved_by = auth.uid(),
    device_credentials = jsonb_build_object(
      'device_id', v_device_id,
      'space_id', p_space_id,
      'device_token', v_device_token
    ),
    updated_at = now()
  where id = v_pairing.id;

  return jsonb_build_object(
    'success', true,
    'device_id', v_device_id,
    'device_name', v_pairing.device_name
  );
end;
$$;

-- Function 3: TV polls or claims the pairing credentials using its secret
create or replace function public.claim_tv_pairing_code(
  p_device_identifier text,
  p_device_secret text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_secret_hash text;
  v_pairing record;
  v_creds jsonb;
begin
  v_secret_hash := encode(sha256(p_device_secret::bytea), 'hex');

  select * into v_pairing
  from public.pairing_codes
  where device_identifier = p_device_identifier
    and device_secret_hash = v_secret_hash
  order by created_at desc
  limit 1
  for update;

  if not found then
    return jsonb_build_object('status', 'not_found');
  end if;

  if v_pairing.expires_at <= now() then
    update public.pairing_codes set status = 'expired' where id = v_pairing.id;
    return jsonb_build_object('status', 'expired');
  end if;

  if v_pairing.status = 'pending' then
    return jsonb_build_object('status', 'pending');
  end if;

  if v_pairing.status = 'approved' then
    v_creds := v_pairing.device_credentials;

    -- Mark claimed and scrub credentials from pairing_codes
    update public.pairing_codes
    set
      status = 'claimed',
      device_credentials = null,
      updated_at = now()
    where id = v_pairing.id;

    return jsonb_build_object(
      'status', 'approved',
      'device_id', v_creds->>'device_id',
      'space_id', v_creds->>'space_id',
      'device_token', v_creds->>'device_token'
    );
  end if;

  return jsonb_build_object('status', v_pairing.status);
end;
$$;

-- ----------------------------------------------------------------------------
-- Function 4: Family Member Invitation Acceptance (Feature F03)
-- ----------------------------------------------------------------------------
create or replace function public.accept_space_invite(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_clean_token text;
  v_caller_email text;
  v_invite record;
  v_member_id uuid;
begin
  -- 1. Ensure caller is authenticated
  if auth.uid() is null then
    raise exception 'Authentication required to accept invitation';
  end if;

  -- 2. Extract and validate caller email from JWT claims (or auth.users fallback)
  v_caller_email := lower(trim(coalesce(
    auth.jwt()->>'email',
    (select email from auth.users where id = auth.uid())
  )));

  if v_caller_email is null or v_caller_email = '' then
    raise exception 'Authenticated user has no verified email address';
  end if;

  -- 3. Sanitize token input
  v_clean_token := trim(p_token);
  if v_clean_token is null or v_clean_token = '' then
    raise exception 'Invitation token is required';
  end if;

  -- 4. Locate and lock pending invitation record
  select * into v_invite
  from public.invites
  where token = v_clean_token
    and status = 'pending'
    and expires_at > now()
    and lower(email) = v_caller_email
  for update;

  if not found then
    raise exception 'Invalid, expired, or unauthorized invite token';
  end if;

  -- 5. Insert or update membership in target space
  insert into public.members (
    space_id,
    user_id,
    role,
    display_name
  ) values (
    v_invite.space_id,
    auth.uid(),
    v_invite.role,
    coalesce(
      nullif(trim(auth.jwt()->>'name'), ''),
      nullif(trim(auth.jwt()->>'full_name'), ''),
      split_part(v_caller_email, '@', 1)
    )
  )
  on conflict (space_id, user_id) do update set
    role = case
      when members.role = 'owner' then 'owner' -- Never downgrade space owner
      else excluded.role
    end,
    updated_at = now()
  returning id into v_member_id;

  -- 6. Transition invitation status to 'accepted'
  update public.invites
  set
    status = 'accepted',
    updated_at = now()
  where id = v_invite.id;

  -- 7. Return success payload
  return jsonb_build_object(
    'success', true,
    'space_id', v_invite.space_id,
    'member_id', v_member_id,
    'role', v_invite.role
  );
end;
$$;

