-- Table 10: bookmarks (Reading progress and page bookmarks for PDF/docs)
create table if not exists public.bookmarks (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  file_id uuid not null references public.files(id) on delete cascade,
  user_id uuid references auth.users(id) on delete cascade,
  device_id uuid references public.devices(id) on delete cascade,
  page_number integer not null check (page_number >= 1),
  scroll_position numeric(6, 4) not null default 0.0000 check (scroll_position between 0.0 and 1.0),
  label text,
  is_last_read boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_bookmarks_actor check (user_id is not null or device_id is not null)
