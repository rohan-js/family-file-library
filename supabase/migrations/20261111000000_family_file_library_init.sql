  on public.bookmarks for delete
  using (
    public.has_space_access(space_id) and (
      (auth.uid() is not null and user_id = auth.uid())
      or (device_id is not null and device_id = public.get_auth_device_id())
      or public.is_space_admin(space_id)
    )
  );

